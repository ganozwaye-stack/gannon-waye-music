export function findStoreProduct(productKey) {
  const resolvedId = STORE_PRODUCT_ALIASES[productKey] || productKey;
  return STORE_PRODUCTS.find(product => product.id === resolvedId);
}

export function toMerchProduct(product) {
  return {
    id: product.id,
    name: product.name,
    description: product.description,
    category: product.category,
    sale_price: product.sale_price ?? product.priceValue,
    cost_price: product.cost_price,
    image_url: product.image_url || product.images?.[0],
    images_array: product.images_array || product.images || [],
    sizes_available: product.sizes_available || product.options?.size || [],
    stock_quantity: product.stock_quantity ?? 0,
    is_active: Boolean(product.is_active),
    excludeFromDiscounts: Boolean(product.excludeFromDiscounts),
  };
}
