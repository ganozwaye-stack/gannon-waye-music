function r(path, workspace, classification, inSidebar, recommendation) {
  const label = path
    .replace('/admin/', '')
    .split('/')
    .pop()
    .split('-')
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
  return { path, label, workspace, classification, inSidebar, recommendation };
}

