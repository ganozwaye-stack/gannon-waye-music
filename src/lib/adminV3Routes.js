// Stats helper
export function getRouteStats() {
  const total = LEGACY_ROUTES.length;
  const byWorkspace = {};
  const byClassification = {};
  const inSidebar = LEGACY_ROUTES.filter(r => r.inSidebar).length;
  LEGACY_ROUTES.forEach(route => {
    byWorkspace[route.workspace] = (byWorkspace[route.workspace] || 0) + 1;
    byClassification[route.classification] = (byClassification[route.classification] || 0) + 1;
  });
  return { total, byWorkspace, byClassification, inSidebar, notInSidebar: total - inSidebar };
}