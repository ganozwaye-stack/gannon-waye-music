export const LIVE_RETAIL_PRODUCT_GALLERIES = Object.fromEntries(
  LIVE_RETAIL_PRODUCTS
    .filter((product) => Array.isArray(product.images_array) && product.images_array.length > 0)
    .map((product) => [product.id, product.images_array])
);

export const featuredRetailProducts = (limit = 4) => {
  const inStock = LIVE_RETAIL_PRODUCTS.filter(
    (product) => product.category !== 'cd' && product.stock_quantity !== 0
  );

  return [...inStock]
    .sort((a, b) => {
      const aFeatured = a.is_featured ? 0 : 1;
      const bFeatured = b.is_featured ? 0 : 1;
      if (aFeatured !== bFeatured) return aFeatured - bFeatured;
      return Number(b.sale_price ?? b.price ?? 0) - Number(a.sale_price ?? a.price ?? 0);
    })
    .slice(0, limit);
};
